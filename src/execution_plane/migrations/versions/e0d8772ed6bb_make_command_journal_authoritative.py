def _preflight() -> None:
    connection = op.get_bind()
    # Holding all four tables prevents receipt/handler writes between validation
    # and transfer. The cutover is one transaction with PostgreSQL transactional DDL.
    connection.execute(
        sa.text("""
        LOCK TABLE execution_plane.exchange_journal, execution_plane.command_records,
            execution_plane.resource_revisions, execution_plane.command_cancellation_intents,
            execution_plane.work_items
        IN ACCESS EXCLUSIVE MODE
    """)
    )
    checks = {
        "commands": """
            SELECT count(*) FROM execution_plane.command_records c
            LEFT JOIN execution_plane.exchange_journal j
              ON j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
            WHERE j.entry_id IS NULL OR j.parent_command_id IS NOT NULL
              OR j.project_id IS DISTINCT FROM c.project_id OR j.all_projects <> c.all_projects
              OR j.source_id <> c.source_id OR j.command_type <> c.command_type
              OR c.status NOT IN ('accepted', 'running', 'succeeded', 'failed', 'cancelled',
                                 'superseded', 'outcome_unknown', 'cancel_requested')
              OR length(c.resource_type) > 64 OR length(c.resource_key) > 255 OR length(c.error_code) > 128
              OR c.desired_revision <= 0 OR c.observed_revision < 0
              OR c.child_sequence > COALESCE((SELECT max(child.parent_sequence)
                  FROM execution_plane.exchange_journal child
                  WHERE child.client_id = c.client_id AND child.parent_command_id = c.command_id
                    AND child.direction = 'outbound'), 0)
        """,
        "resources": """
            SELECT count(*) FROM execution_plane.resource_revisions r
            WHERE r.desired_revision <= 0 OR r.observed_revision < 0
              OR length(r.resource_type) > 64 OR length(r.desired_hash) <> 64
              OR NOT EXISTS (
                SELECT 1 FROM execution_plane.command_records c
                JOIN execution_plane.exchange_journal j
                  ON j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
                WHERE c.client_id = r.client_id AND c.resource_type = r.resource_type
                  AND c.resource_key = r.resource_key AND c.desired_revision = r.desired_revision
                  AND c.project_id IS NOT DISTINCT FROM r.project_id AND c.all_projects = r.all_projects
                  AND c.command_type LIKE r.resource_type || '.%'
              )
              OR EXISTS (
                SELECT 1 FROM execution_plane.command_records c
                WHERE c.client_id = r.client_id AND c.resource_type = r.resource_type
                  AND c.resource_key = r.resource_key
                  AND (c.project_id IS DISTINCT FROM r.project_id OR c.all_projects <> r.all_projects)
              )
        """,
        "unreserved_resources": """
            SELECT count(*) FROM execution_plane.command_records c
            WHERE (c.command_type LIKE 'cluster.%' OR c.command_type LIKE 'execution_target.%')
              AND NOT EXISTS (
                SELECT 1 FROM execution_plane.resource_revisions r
                WHERE r.client_id = c.client_id AND r.resource_type = c.resource_type
                  AND r.resource_key = c.resource_key
              )
        """,
        "cancellations": """
            SELECT count(*) FROM execution_plane.command_cancellation_intents i
            LEFT JOIN execution_plane.exchange_journal j
              ON j.client_id = i.client_id AND j.command_id = i.cancellation_command_id AND j.direction = 'inbound'
            WHERE j.entry_id IS NULL OR j.command_type <> 'command.cancel'
              OR j.parent_command_id IS NOT NULL OR j.project_id IS DISTINCT FROM i.project_id
              OR j.all_projects <> i.all_projects
              OR i.scope_key <> CASE WHEN i.all_projects THEN '*' ELSE CAST(i.project_id AS text) END
              OR (SELECT count(*) FROM execution_plane.command_cancellation_intents other
                  WHERE other.client_id = i.client_id
                    AND other.cancellation_command_id = i.cancellation_command_id) > 1
        """,
    }
    counts = {name: connection.execute(sa.text(query)).scalar_one() for name, query in checks.items()}
    if any(counts.values()):
        message = "Refusing single-journal cutover: " + ", ".join(f"{name}={count}" for name, count in counts.items())
        raise RuntimeError(message)


def _transfer() -> None:
    connection = op.get_bind()
    connection.execute(
        sa.text("""
        UPDATE execution_plane.exchange_journal j SET
            resource_type = c.resource_type, resource_key = c.resource_key, resource_id = c.resource_id,
            desired_revision = c.desired_revision, observed_revision = COALESCE(c.observed_revision, 0),
            command_status = c.status, command_error_code = c.error_code
        FROM execution_plane.command_records c
        WHERE j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
    """)
    )
    # The former query overlay exposed the provider's pending cancellation.
    # Preserve that durable state only through its exact command association;
    # bounded terminal outcomes in CommandRecord remain authoritative.
    connection.execute(
        sa.text("""
        UPDATE execution_plane.exchange_journal j SET command_status = 'cancel_requested'
        FROM execution_plane.command_records c
        JOIN execution_plane.work_items w
          ON c.resource_type = 'work_item' AND c.resource_id = w.id
            AND c.client_id = w.client_id AND c.project_id = w.project_id
            AND w.request_id = CAST(c.command_id AS text)
        WHERE j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
          AND c.command_type = 'work.execute' AND c.status IN ('accepted', 'running', 'cancel_requested')
          AND w.status = 'cancel_requested'
    """)
    )
    # Equal revisions accepted by the old store have equal hashes. Choose their
    # newest accepted command deterministically; the journal row remains a real command.
    connection.execute(
        sa.text("""
        WITH heads AS (
            SELECT DISTINCT ON (r.client_id, r.resource_type, r.resource_key)
                j.entry_id, r.desired_hash, r.resource_id, r.observed_revision, r.deleted
            FROM execution_plane.resource_revisions r
            JOIN execution_plane.command_records c
              ON c.client_id = r.client_id AND c.resource_type = r.resource_type
                AND c.resource_key = r.resource_key AND c.desired_revision = r.desired_revision
            JOIN execution_plane.exchange_journal j
              ON j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
            ORDER BY r.client_id, r.resource_type, r.resource_key, c.created_at DESC, c.command_id DESC
        )
        UPDATE execution_plane.exchange_journal j SET resource_head = true,
            desired_hash = h.desired_hash, resource_id = h.resource_id,
            observed_revision = h.observed_revision, resource_deleted = h.deleted
        FROM heads h WHERE j.entry_id = h.entry_id
    """)
    )
    connection.execute(
        sa.text("""
        UPDATE execution_plane.exchange_journal j SET target_command_id = i.target_command_id
        FROM execution_plane.command_cancellation_intents i
        WHERE j.client_id = i.client_id AND j.command_id = i.cancellation_command_id AND j.direction = 'inbound'
    """)
    )
    # running/unknown means initial domain mutation committed. Fence old claims
    # and resume observation, even when the old journal considered handling done.
    connection.execute(
        sa.text("""
        UPDATE execution_plane.exchange_journal j SET observation_pending = true,
            handling_state = 'deferred', handling_due_at = now(), handling_owner = NULL,
            handling_lease_until = NULL, handling_generation = handling_generation + 1
        FROM execution_plane.command_records c
        WHERE j.client_id = c.client_id AND j.command_id = c.command_id AND j.direction = 'inbound'
          AND c.status IN ('running', 'outcome_unknown')
          AND (c.command_type LIKE 'cluster.%' OR c.command_type LIKE 'execution_target.%'
               OR c.command_type = 'command.cancel')
    """)
    )


